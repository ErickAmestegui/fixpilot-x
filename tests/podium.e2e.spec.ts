import {test,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import {startMcpServer} from '../server/mcp';
let server:Awaited<ReturnType<typeof startMcpServer>>;
test.beforeAll(async()=>{server=await startMcpServer(3101);});
test.afterAll(async()=>{await server.close();});
test.use({video:{mode:'on',size:{width:1280,height:900}},viewport:{width:1280,height:900}});

for(const part of ['B7','B1'])test(`Judge Mode calculates ${part}, compares independent recovery and preserves confirmations`,async({page})=>{
 const requests:unknown[]=[];page.on('request',r=>{if(r.url()===server.url&&r.method()==='POST'){const body=r.postDataJSON();if(body.method==='tools/call')requests.push(body.params);}});
 await page.goto('/?judge');
 const saved=await page.evaluate(()=>JSON.stringify(localStorage));
 await expect(page.getByRole('heading',{name:'New setback.'})).not.toBeVisible();
 await page.getByRole('button',{name:'Connect real MCP',exact:true}).click();
 await page.getByRole('button',{name:'Start guided rescue'}).click();
 await expect(page.getByTestId('challenge-ready')).toHaveText('3, 4, 6');
 await expect(page.getByRole('button',{name:'Apply to challenge record',exact:true})).toBeDisabled();
 await page.getByLabel('Judge challenge part').selectOption(part);
 await page.getByRole('button',{name:'Preview missing part',exact:true}).click();
 await expect(page.getByRole('button',{name:`${part}:`,exact:false}).first()).toHaveClass(/is-missing/);
 await expect(page.getByLabel('I reviewed this challenge change')).toBeEnabled();
 await page.getByLabel('I reviewed this challenge change').check();
 await page.getByRole('button',{name:'Preview missing part',exact:true}).click();
 await expect(page.getByLabel('I reviewed this challenge change')).toBeEnabled();
 await expect(page.getByLabel('I reviewed this challenge change')).not.toBeChecked();
 await expect(page.getByRole('button',{name:part+':',exact:false}).first()).toHaveClass(/is-missing/);
 await page.getByLabel('I reviewed this challenge change').check();
 await page.getByRole('button',{name:'Apply to challenge record',exact:true}).click();
 await expect(page.locator('.challenge-final')).toContainText(`Missing: ${part}`);
 const reports=part==='B7'?'2/8':'1/8';await expect(page.locator('.challenge-final')).toContainText(reports);
 await expect(page.getByRole('button',{name:'Compare: keep missing vs recover'})).toBeEnabled();
 await page.getByRole('button',{name:'Compare: keep missing vs recover'}).click();
 const alternatives=page.locator('.challenge-comparison article');await expect(alternatives).toHaveCount(2);
 await expect(alternatives.nth(0)).toContainText(part);await expect(alternatives.nth(1)).toContainText('No missing parts');
 await expect(page.locator('.challenge-final')).toContainText(`Missing: ${part}`);
 await page.getByRole('button',{name:'Preview recovery in 3D'}).click();
 await expect(page.getByLabel('I reviewed this challenge change')).toBeEnabled();
 await expect(page.getByLabel('I reviewed this challenge change')).not.toBeChecked();
 await expect(page.getByRole('button',{name:'Apply to challenge record',exact:true})).toBeDisabled();
 await page.getByLabel('I reviewed this challenge change').check();
 await page.getByRole('button',{name:'Apply to challenge record',exact:true}).click();
 await expect(page.locator('.challenge-final')).toContainText('Missing: None');
 await expect(page.locator('.challenge-final')).toContainText(reports);
 await expect(page.getByRole('heading',{name:'Recovery recorded; work still needs confirmation'})).toBeVisible();
 expect(await page.evaluate(()=>JSON.stringify(localStorage))).toEqual(saved);
 const pending=page.waitForEvent('download');await page.getByRole('button',{name:'Export evidence JSON'}).click();
 await mkdir('docs/podium-evidence',{recursive:true});await(await pending).saveAs(`docs/podium-evidence/judge-${part}.json`);
 for(const tool of ['preview_scenario','compare_scenarios','apply_scenario'])expect(JSON.stringify(requests)).toContain(tool);
 await writeFile(`docs/podium-evidence/judge-${part}-requests.json`,JSON.stringify({mocked:false,requests},null,2));
 await page.screenshot({path:`docs/podium-evidence/judge-${part}.png`});
 await mkdir('demo-podium-results',{recursive:true});const video=page.video();await page.close();await video?.saveAs(`demo-podium-results/judge-${part}.webm`);
});

