 await expect(page.getByTestId('challenge-blocked')).toHaveText('4, 6');
 await page.getByLabel('I reviewed this challenge change').check();await page.getByRole('button',{name:'Apply to challenge record',exact:true}).click();
 await expect(page.locator('.challenge-final')).toContainText('Missing: O5');
 await page.getByRole('button',{name:'Preview recovery in 3D'}).click();await expect(page.getByLabel('I reviewed this challenge change')).toBeEnabled();
 await page.getByLabel('I reviewed this challenge change').check();await page.getByRole('button',{name:'Apply to challenge record',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Recovery recorded; work still needs confirmation'})).toBeVisible();
 await page.getByRole('button',{name:'Explore another scenario'}).click();
