 await page.goto('/?challenge');await page.getByLabel('Challenge assembly',{exact:true}).selectOption('organizer');
 await page.getByRole('button',{name:'Enter Judge Mode'}).click();await page.getByRole('button',{name:'Start guided rescue'}).click();
 await expect(page.getByLabel('Judge challenge part')).toHaveValue('O1');
