 await expect(page.getByLabel('Challenge B7',{exact:true})).toBeVisible();
 await expect(page.locator('.challenge-final')).toContainText('2/8');
 await page.getByRole('button',{name:'Enter Judge Mode'}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await page.screenshot({path:'docs/podium-evidence/judge-mobile.png',fullPage:true});
